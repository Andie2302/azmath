#!/usr/bin/env python3
"""Generate IEEE reference vectors. Requires mpmath 1.3.0; not needed by cargo test."""
import math
import struct
from pathlib import Path
import mpmath as mp


def bits(v, width):
    """Round high precision to nearest IEEE value, ties to even (no double rounding)."""
    fb, eb = (23, 8) if width == 32 else (52, 11)
    sign = int(v < 0)
    v = abs(v)
    if not v:
        return 0
    bias = (1 << (eb - 1)) - 1
    e = max(int(mp.floor(mp.log(v, 2))), 1 - bias)
    scaled = v / mp.power(2, e - fb)
    m = int(mp.floor(scaled))
    tail = scaled - m
    m += int(tail > mp.mpf('0.5') or (tail == mp.mpf('0.5') and m % 2))
    if m >= 1 << (fb + 1):
        m >>= 1
        e += 1
    if e > bias:
        return (sign << (width - 1)) | (((1 << eb) - 1) << fb)
    exponent = 0 if m < 1 << fb else e + bias
    fraction = m if exponent == 0 else m - (1 << fb)
    return (sign << (width - 1)) | (exponent << fb) | fraction


xs = ['1e-30', '1e-200', '0.1', '0.5', '1', '1.0000001192092896',
      '1.0000000000000002', '1.5', '2', '2.0000000000000004', '4.25',
      '10.5', '30.25', '100.5', '170.5', '-0.1', '-0.5', '-1.5',
      '-10.000000000000002', '-170.5', '-171.5']
cases = [(f, 0, x) for f in ['gamma', 'ln_gamma'] for x in xs]
cases += [(f, 0, x) for f in ['erf', 'erfc'] for x in
          ['-10', '-3', '-1', '-0.01', '0', '1e-30', '1e-200', '0.01',
           '0.125', '0.5', '1', '2', '3', '5', '8', '10', '20']]
cases += [(f, n, x) for f in ['bessel_j', 'bessel_i', 'bessel_y', 'bessel_k']
          for n in [0, 1, 2, 5, 10] for x in ['0.001', '0.5', '1', '5', '20']]
# Tiny arguments exercise recurrence scaling and gradual underflow.
cases += [('bessel_j', n, x) for n in [0, 1, 2] for x in ['1e-30', '1e-200']]
# Regression found by libFuzzer: adaptive roundoff floor with f32.
cases += [('bessel_y', 3, '0.23702975')]
rows = []
for width in [32, 64]:
    fmt, integer = ('f', 'I') if width == 32 else ('d', 'Q')
    seen = set()
    for name, n, text in cases:
        packed = struct.pack('>' + fmt, float(text))
        x = struct.unpack('>' + fmt, packed)[0]
        xb = struct.unpack('>' + integer, packed)[0]
        if name in ['gamma', 'ln_gamma'] and x <= 0 and x == math.floor(x):
            continue
        key = name, n, xb
        if key in seen:
            continue
        seen.add(key)
        numerator, denominator = x.as_integer_ratio()
        answers = []
        for precision in [100, 200]:
            with mp.workdps(precision):
                a = mp.mpf(numerator) / denominator
                if name == 'ln_gamma':
                    y = mp.log(abs(mp.gamma(a)))
                elif name.startswith('bessel_'):
                    y = getattr(mp, name.replace('_', ''))(n, a)
                else:
                    y = getattr(mp, name)(a)
                answers.append(bits(y, width))
        assert answers[0] == answers[1], (key, answers)
        rows.append(f'    ("{name}", {n}, {width}, 0x{xb:016x}, 0x{answers[0]:016x}),')
header = f'// Generated by scripts/generate_special_refs.py, mpmath {mp.__version__}.\n'
header += '// Exactly rounded inputs; references agree at 100 and 200 decimal digits.\n'
header += 'pub const CASES: &[(&str, u32, u32, u64, u64)] = &[\n'
Path('tests/data/special_refs.rs').write_text(header + '\n'.join(rows) + '\n];\n')
print(f'Generated {len(rows)} reference vectors')
